export function generateItemCode(mainCategory: string, existingItems: Item[]): string {
  const baseMap: Record<string, number> = {
    CAT1: 10000,
    CAT2: 20000,
    CAT3: 30000,
  };
  const base = baseMap[mainCategory] || 90000;
  const prefix = String(base / 10000);

  const matchedNumbers = existingItems
    .filter((x) => x.code.startsWith(prefix) && /^\d+$/.test(x.code))
    .map((x) => parseInt(x.code, 10));

  const maxVal = Math.max(base, ...matchedNumbers);
  return String(maxVal + 1);
}

export function toItemListSummary(item: Item, companyIdFilter?: string): ItemListSummary {
  const allocatedCompanyIds = item.companies
    .filter((c) => c.is_allocated)
    .map((c) => c.company_id);

  // Check company settings if company filter applied, otherwise check default (101) or any
  const settings =
    companyIdFilter && item.company_settings[companyIdFilter]
      ? item.company_settings[companyIdFilter]
      : item.company_settings["101"] || Object.values(item.company_settings)[0] || {
        is_inventory: true,
        is_sales: true,
        is_purchase: true,
        is_production: false,
      };

  return {
    code: item.code,
    name: item.name,
    description: item.description,
    main_category: item.main_category,
    main_category_name: item.main_category_name,
    sub_category: item.sub_category,
    brand: item.brand,
    base_uom: item.base_uom,
    companies: allocatedCompanyIds,
    is_active: item.is_active,
    is_inventory: settings.is_inventory,
    is_sales: settings.is_sales,
    is_purchase: settings.is_purchase,
    is_production: settings.is_production,
    barcode: item.barcode,
    supplier_code: item.supplier_code,
  };
}
